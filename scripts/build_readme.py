"""Compose the profile from content/profile.json and typed visual modules."""
from html import escape
from profile_design.shared import ROOT, PROFILE


def picture(stem, alt, animated=True):
    lines=['<picture>']
    if animated:
        for compact in (True,False):
            for theme in ('dark','light'):
                media=('(max-width: 900px) and ' if compact else '')+f'(prefers-reduced-motion: reduce) and (prefers-color-scheme: {theme})'
                suffix='-mobile' if compact else ''
                lines.append(f'  <source media="{media}" srcset="{stem}{suffix}-static-{theme}.svg">')
    for compact in (True,False):
        for theme in ('dark','light'):
            media=('(max-width: 900px) and ' if compact else '')+f'(prefers-color-scheme: {theme})'
            suffix='-mobile' if compact else ''
            lines.append(f'  <source media="{media}" srcset="{stem}{suffix}-{theme}.svg">')
    lines.append(f'  <img src="{stem}-dark.svg" width="100%" alt="{escape(alt,quote=True)}">')
    return '\n'.join(lines+['</picture>'])


def heading(index):
    data=PROFILE['sections'][index-1]
    return '<h2>\n'+picture(f'assets/modules/section-{index:02}-{data["key"]}',f'{index:02} / '+data['title'])+'\n</h2>'


def contribution_trace():
    lines=['<picture>']
    for compact in (True,False):
        for theme in ('dark','light'):
            media=('(max-width: 900px) and ' if compact else '')+f'(prefers-reduced-motion: reduce) and (prefers-color-scheme: {theme})'
            suffix='-mobile' if compact else ''
            lines.append(f'  <source media="{media}" srcset="assets/generated/activity-calendar{suffix}-{theme}.svg">')
    for theme in ('dark','light'):
        lines.append(f'  <source media="(prefers-color-scheme: {theme})" srcset="assets/generated/contribution-snake-{theme}.svg">')
    lines.append('  <img src="assets/generated/contribution-snake-dark.svg" width="100%" alt="Animated contribution snake from Lokesh\'s real GitHub calendar. Reduced motion selects the static calendar.">')
    return '\n'.join(lines+['</picture>'])


